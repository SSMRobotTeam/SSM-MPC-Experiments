from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


def _load_csv(path: Path) -> dict[str, np.ndarray]:
    with path.open("r", newline="", encoding="utf-8-sig") as file:
        reader = csv.DictReader(file)
        if reader.fieldnames is None:
            raise ValueError(f"No header found in {path}")

        columns: dict[str, list[float | str]] = {name: [] for name in reader.fieldnames}
        for row in reader:
            for name in reader.fieldnames:
                value = row[name]
                try:
                    columns[name].append(float(value))
                except ValueError:
                    columns[name].append(value)

    return {
        name: np.asarray(values, dtype=float) if values and isinstance(values[0], float) else np.asarray(values)
        for name, values in columns.items()
    }


def plot_s0_first_element(
    time_s: np.ndarray,
    s0_1: np.ndarray,
    output_path: Path,
) -> plt.Figure:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(11, 5), constrained_layout=True)
    ax.plot(time_s, s0_1, color="#0072B2", linewidth=1.8)
    ax.set_title(r"Estimated $S_{0,1}(t)$")
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("S0_1")
    ax.grid(True, linestyle="--", linewidth=0.6, alpha=0.45)
    fig.savefig(output_path, dpi=300)
    return fig


def parse_args() -> argparse.Namespace:
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description="Plot the first element of the estimated S0 sequence.")
    parser.add_argument(
        "--input",
        type=Path,
        default=script_dir / "results" / "S0_est" / "estimated_S0_sequence.csv",
        help="CSV generated by S0_est.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=script_dir / "results" / "S0_est" / "estimated_S0_1_time.png",
        help="Output figure path.",
    )
    parser.add_argument("--show", action="store_true", help="Show the figure interactively after saving.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    data = _load_csv(args.input)
    if "time_s" not in data:
        raise KeyError(f"{args.input} is missing required column: time_s")
    if "S0_1" not in data:
        raise KeyError(f"{args.input} is missing required column: S0_1")

    fig = plot_s0_first_element(
        np.asarray(data["time_s"], dtype=float),
        np.asarray(data["S0_1"], dtype=float),
        args.output,
    )
    print(f"Saved S0_1 time plot to {args.output}")

    if args.show:
        plt.show()
    else:
        plt.close(fig)


if __name__ == "__main__":
    main()
